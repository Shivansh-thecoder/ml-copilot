"""Structured schemas for the ML Copilot orchestration graph.

Two genuinely LLM-authored schemas (`CopilotPlan`, `FinalNarrative`) plus
`CopilotFinalResponse`, which is NOT LLM-authored as a whole -- see
`nodes/copilot_control.py`'s `finalize_node`. Its numeric/factual fields
(selected_model, primary_metric, validation_performance, ...) are
populated directly from `state["tool_results"]` in Python; only
`FinalNarrative`'s two fields are ever generated by a model call, and
even those are grounded by passing the actual tool results as context.
This split is deliberate: "do not reconstruct metrics from memory inside
the LLM" is enforced structurally here, not just by instruction wording.
"""

from pydantic import BaseModel, Field


class CopilotPlan(BaseModel):
    """The planner's structured output.

    Produced BEFORE any dataset has been inspected, so `target_column`/
    `task_type` must be `None` unless the user's own objective text
    explicitly names them -- the planner has no other way to know either
    yet. Never fabricated; `detect_target_stage` (nodes/copilot_tools.py)
    is what actually resolves these later, grounded in the real data.
    """

    objective: str = Field(description="The user's objective, restated concisely.")
    dataset_id: str
    target_column: str | None = Field(
        default=None,
        description="Target column ONLY if explicitly named in the user's objective text. "
        "Null if not stated -- never guessed from the dataset, which hasn't been inspected yet.",
    )
    task_type: str | None = Field(
        default=None,
        description="'classification' or 'regression' ONLY if it can be determined from the "
        "objective text alone (e.g. an explicitly named target makes this inferable). Null otherwise.",
    )
    intended_analysis_steps: list[str] = Field(
        description="The EDA/inspection steps this workflow intends to run, in plain language."
    )
    intended_modeling_steps: list[str] = Field(
        description="The modeling steps this workflow intends to run, in plain language."
    )


class FinalNarrative(BaseModel):
    """The ONLY part of the final response an LLM actually authors --
    prose, not numbers. See `finalize_node`: this is invoked with the
    real tool results serialized into the prompt, specifically to bound
    what it can say to what's actually in evidence.
    """

    comparison_summary: str = Field(
        description="Plain-English comparison of the candidate models that were actually "
        "evaluated, using ONLY the numbers provided in context -- never invented ones."
    )
    caveats: list[str] = Field(
        description="Important caveats/limitations the user should know about this specific run "
        "(e.g. small dataset, class imbalance, tuning skipped, a step that failed)."
    )


class CopilotFinalResponse(BaseModel):
    """The complete final answer returned to the user.

    Every FACTUAL/numeric field here is populated directly from
    `state["tool_results"]` in `finalize_node` -- not generated by an LLM
    call. Only `comparison_summary` and `caveats` (via `FinalNarrative`)
    are model-authored text.
    """

    success: bool
    objective: str
    dataset_id: str
    target_column: str | None
    task_type: str | None
    selected_model: str | None
    primary_metric: str | None
    validation_performance: str
    comparison_summary: str
    overfitting_diagnostic: str | None
    tuning_performed: bool
    tuning_explanation: str
    saved_model_location: str | None
    caveats: list[str]
    failure_reason: str | None = None
