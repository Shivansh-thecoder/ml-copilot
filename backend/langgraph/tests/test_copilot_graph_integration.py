"""Integration tests: the REAL MCP client spawns the REAL MCP server
subprocess, which runs the REAL ml_engine against a REAL seeded dataset --
only the LLM is mocked (scripted responses), keeping this deterministic
and free while still proving LangGraph -> MCP client -> MCP server ->
ML tool actually works end to end, not just each piece in isolation.

Deliberately few of these -- the bulk of coverage is in
test_copilot_graph_mocked.py, which runs in a fraction of the time since
it never spawns a subprocess.
"""

import csv
import re
import sqlite3
import uuid
from datetime import datetime, timezone
from pathlib import Path

import pytest

from graphs.copilot_graph import build_copilot_graph
from schemas.copilot import CopilotPlan, FinalNarrative
from tests.conftest import tool_call_message

_BACKEND_DIR = Path(__file__).resolve().parents[2]  # tests -> langgraph -> backend
_DB_PATH = _BACKEND_DIR / "app.db"
_STORAGE_DIR = _BACKEND_DIR / "storage" / "datasets"


@pytest.fixture
def real_dataset():
    """Seed a real row into backend/app.db + a real CSV under
    backend/storage/datasets/ -- exactly the convention
    app/services/dataset_service.py uses -- so the REAL MCP server (a
    separate process/interpreter) can actually find and load it. Cleans
    up both the row/file and any ml_engine artifacts it produces."""
    _STORAGE_DIR.mkdir(parents=True, exist_ok=True)

    rng_rows = []
    for i in range(60):
        age = 20 + (i * 3) % 50
        tenure = 1 + (i * 7) % 60
        monthly_charge = 20 + (i * 5) % 100
        churned = 1 if (tenure < 12 and monthly_charge > 60) else 0
        rng_rows.append((age, tenure, monthly_charge, churned))

    dataset_id = str(uuid.uuid4())
    filename = f"{dataset_id}_integration_test.csv"
    csv_path = _STORAGE_DIR / filename
    with csv_path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["age", "tenure_months", "monthly_charge", "churned"])
        writer.writerows(rng_rows)

    stored_path = str(Path("storage") / "datasets" / filename)
    conn = sqlite3.connect(str(_DB_PATH))
    conn.execute(
        "INSERT INTO datasets (id, name, target_column, rows, columns, size_bytes, stored_path, uploaded_at) "
        "VALUES (?,?,?,?,?,?,?,?)",
        (dataset_id, "integration_test", "", 60, 4, csv_path.stat().st_size, stored_path, datetime.now(timezone.utc).isoformat()),
    )
    conn.commit()
    conn.close()

    try:
        yield dataset_id
    finally:
        conn = sqlite3.connect(str(_DB_PATH))
        conn.execute("DELETE FROM datasets WHERE id = ?", (dataset_id,))
        conn.commit()
        conn.close()
        csv_path.unlink(missing_ok=True)

        # ml_engine artifacts this run produced
        mcp_storage = _BACKEND_DIR / "mcp" / "storage"
        exp_db = mcp_storage / "experiments.db"
        if exp_db.exists():
            exp_conn = sqlite3.connect(str(exp_db))
            exp_conn.execute("DELETE FROM experiments WHERE dataset_id = ?", (dataset_id,))
            exp_conn.commit()
            exp_conn.close()
        for pattern in [f"{dataset_id}.*"]:
            for p in (mcp_storage / "saved").glob(pattern):
                p.unlink(missing_ok=True)


def _extract(pattern: str, text: str) -> str:
    match = re.search(pattern, text)
    assert match, f"pattern {pattern!r} not found in instruction text: {text!r}"
    return match.group(1)


def test_real_mcp_round_trip_end_to_end(mock_llm, real_dataset):
    """Full graph run against the REAL MCP server/ML engine. Verifies the
    final response's numbers are literally the ones the ML engine
    produced -- not regenerated by the (mocked) LLM."""
    dataset_id = real_dataset

    def smart_response(messages):
        """One universal dispatcher for every tool-calling stage, keyed
        off the ACTUAL instruction text rather than call position.

        Needed because this test can't know in advance: (a) whether
        tune_decision_node decides to tune (a genuine, data-dependent
        Python decision reading the REAL training diagnostic), and
        (b) whether any stage needs `run_tool_stage`'s internal retry
        (e.g. a transient real ML-engine issue on a tiny synthetic
        dataset) -- either would shift a POSITIONAL queue out of sync.
        Dispatching on content makes the exact call count irrelevant;
        `mock_llm`'s tool queue just needs enough copies of this to
        cover the worst case (every stage retrying once).
        """
        instruction = messages[-1].content
        if instruction.startswith("Inspect the structure"):
            return tool_call_message("inspect_dataset", {"dataset_id": dataset_id})
        if instruction.startswith("Run exploratory data analysis"):
            return tool_call_message("profile_dataset", {"dataset_id": dataset_id})
        if instruction.startswith("Determine the target column"):
            return tool_call_message("detect_target", {"dataset_id": dataset_id, "target_column": "churned"})
        if instruction.startswith("Train and compare"):
            return tool_call_message(
                "train_models", {"dataset_id": dataset_id, "target_column": "churned", "task_type": "classification"}
            )
        if "hyperparameter search" in instruction:
            model_name = _extract(r"for the '([^']+)' model", instruction)
            return tool_call_message(
                "tune_model",
                {
                    "dataset_id": dataset_id,
                    "model_name": model_name,
                    "target_column": "churned",
                    "task_type": "classification",
                    "n_iter": 3,
                    "cv_folds": 2,
                },
            )
        if instruction.startswith("Save the"):
            model_name = _extract(r"Save the '([^']+)' model", instruction)
            run_id = _extract(r"from run '([^']+)'", instruction)
            return tool_call_message(
                "save_model", {"dataset_id": dataset_id, "run_id": run_id, "model_name": model_name}
            )
        if instruction.startswith("Retrieve the experiment"):
            return tool_call_message("get_experiment_results", {"dataset_id": dataset_id})
        raise AssertionError(f"smart_response: no dispatch rule for instruction: {instruction!r}")

    mock_llm(
        [
            CopilotPlan(
                objective="Predict churn.",
                dataset_id=dataset_id,
                target_column=None,
                task_type=None,
                intended_analysis_steps=["Inspect", "Profile"],
                intended_modeling_steps=["Train", "Evaluate"],
            ),
            *([smart_response] * 12),  # generous headroom for up to 2 attempts per stage (6 stages)
            FinalNarrative(comparison_summary="Real end-to-end run.", caveats=["Small synthetic test dataset."]),
        ]
    )

    graph = build_copilot_graph()
    config = {"configurable": {"thread_id": f"integration-{dataset_id}"}}
    initial_state = {
        "objective": "Predict churn.",
        "dataset_id": dataset_id,
        "plan": None,
        "target_column": "churned",
        "task_type": None,
        "messages": [],
        "tool_results": [],
        "current_step": "start",
        "completed_steps": [],
        "errors": [],
        "needs_clarification": False,
        "clarification_question": None,
        "run_id": None,
        "selected_model": None,
        "tuning_performed": False,
        "tuning_reason": "",
        "saved_model_info": None,
        "final_response": None,
        "iteration_count": 0,
        "tool_call_count": 0,
        "consecutive_failures": 0,
    }

    result = graph.invoke(initial_state, config)

    # -- structural assertions --
    assert "__interrupt__" not in result
    response = result["final_response"]
    assert response.success is True
    assert response.selected_model is not None

    # -- grounding assertions: the response's numbers must be the ACTUAL
    # ml_engine numbers, traceable back through tool_results, not
    # anything the (scripted, non-numeric) LLM could have invented --
    train_result = next(r["result"] for r in result["tool_results"] if r["stage"] == "train")
    best = next(r for r in train_result["results"] if r["model"] == response.selected_model)
    primary_metric = train_result["primary_metric"] if not result["tuning_performed"] else response.primary_metric
    if not result["tuning_performed"]:
        expected_score = best["cv_mean"][primary_metric]
        assert f"{expected_score:.4f}" in response.validation_performance

    # the saved model artifact must actually exist on disk
    if response.saved_model_location:
        assert Path(response.saved_model_location).exists()

    # narrative fields came from the (mocked) LLM, but factual fields did not
    assert response.comparison_summary == "Real end-to-end run."
    assert response.caveats == ["Small synthetic test dataset."]
